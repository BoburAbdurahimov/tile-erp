let CURRENT_LANG = localStorage.getItem("erp_lang") || "uz";

function t(key) {
  return (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]) || key;
}

function setLanguage(lang) {
  if (lang === "uz" || lang === "ru") {
    CURRENT_LANG = lang;
    localStorage.setItem("erp_lang", lang);
    applyTranslations();
  }
}
